"""Generate the three cumulative energy bands used by Medley's bundled Grand Piano.

From the repository root (developer-only dependencies: numpy and soundfile):
  python tools/calibrate_medley_piano.py > forge-rs/src/medley_piano_profiles.rs

The exporter consumes just the quantized table, never the MP3s or this script.
"""
import base64
import io
import re
from pathlib import Path

import numpy as np
import soundfile as sf

BANK = Path(__file__).resolve().parents[1] / 'renderer/soundfonts/FluidR3_GM/acoustic_grand_piano-mp3.js'
RATE = 44100
TIMES = np.array([0., .0125, .025, .05, .075, .1, .15, .2, .3, .45, .65, 1., 1.5, 2.25, 3.25, 5.])
FRAMES = np.rint(TIMES * RATE).astype(int)


def load_bank():
    bank = {}
    for letter, sharp, octave, data in re.findall(r'"([A-G])(#?)(-?\d+)"\s*:\s*"data:audio/[^;]+;base64,([^"\s]+)"', BANK.read_text()):
        pitch = 12 * (int(octave) + 1) + 'C D EF G A B'.index(letter) + bool(sharp)
        wave, rate = sf.read(io.BytesIO(base64.b64decode(data, validate=True)), dtype='float32', always_2d=True)
        if rate != RATE:
            raise ValueError(f'{pitch}: expected {RATE} Hz, got {rate}')
        bank[pitch] = wave
    return bank


def profile(bank, pitch):
    key = min(bank, key=lambda p: (abs(p - pitch), p))
    mono = bank[key].mean(axis=1).astype('float64')
    if pitch != key:
        pos = np.arange(0, len(mono) - 1, 2 ** ((pitch - key) / 12))
        mono = np.interp(pos, np.arange(len(mono)), mono)
    attack = round(0.004 * RATE)
    mono[:attack] *= np.linspace(0, 1, attack)
    total = np.r_[0., np.cumsum(mono ** 2)][FRAMES.clip(max=len(mono))] / RATE

    blocks = mono[:len(mono) // 128 * 128].reshape(-1, 128)
    def box_power(size):
        return (blocks.reshape(len(blocks), -1, size).mean(axis=2) ** 2).mean(axis=1)

    def block_energy(power):
        # Spread each block's measured energy uniformly over its 128 samples.
        energy = np.r_[0., np.cumsum(power)] * (128 / RATE)
        return np.interp(FRAMES / 128, np.arange(len(energy)), energy)

    low = block_energy(box_power(128))
    mid = block_energy((box_power(8) - box_power(64)).clip(min=0))
    curves = np.array([total, low, mid])
    unit = curves[:, -1] / 65535
    if not np.all(unit > 0):
        raise ValueError(f'{pitch}: silent calibration band')
    return unit, np.rint(curves / unit[:, None]).astype('uint16')


if __name__ == '__main__':
    bank = load_bank()
    print('// Generated by tools/calibrate_medley_piano.py; do not edit by hand.')
    print('const TIMES: [f64; %d] = [%s];' % (len(TIMES), ', '.join(map(str, TIMES))))
    print('#[rustfmt::skip]')
    print('const PROFILES: [Profile; 88] = [')
    for pitch in range(21, 109):
        unit, codes = profile(bank, pitch)
        # Each CDF starts at zero. Keep its other 15 knots; all keys and bands
        # retain their own scale so quiet treble notes do not lose precision.
        scales = ', '.join('%.9e' % x for x in unit)
        rows = ', '.join('[' + ', '.join(map(str, row[1:])) + ']' for row in codes)
        print(f'    Profile {{ unit: [{scales}], cdf: [{rows}] }},')
    print('];')
