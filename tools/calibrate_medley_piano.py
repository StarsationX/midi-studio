"""Measure cumulative energy and pitched attack levels of Medley's bundled Grand Piano.

From the repository root (developer-only dependencies: numpy and soundfile):
  python tools/calibrate_medley_piano.py > forge-rs/src/medley_piano_profiles.rs
  python tools/calibrate_medley_piano.py --spectra > forge-rs/src/medley_piano_spectra.rs
  python tools/calibrate_medley_piano.py --reference forge-rs/src/medley_reference.pcm
  python tools/calibrate_medley_piano.py --bands > forge-rs/src/medley_recording_profiles.rs

The --bands and --reference calibrations also use scipy.signal.

The exporter consumes the calibrated tables and mono analysis reference, not the MP3s or this script.
"""
import base64
import io
import re
import sys
from pathlib import Path

import numpy as np
import soundfile as sf

BANK = Path(__file__).resolve().parents[1] / 'renderer/soundfonts/FluidR3_GM/acoustic_grand_piano-mp3.js'
RATE = 44100
TIMES = np.array([0., .0125, .025, .05, .075, .1, .15, .2, .3, .45, .65, 1., 1.5, 2.25, 3.25, 5.])
FRAMES = np.rint(TIMES * RATE).astype(int)
AGES = [-.06, -.025, 0., .025, .05, .09, .16, .28, .46, .76, 1.25, 2., 3.4]


def load_bank():
    bank = {}
    for letter, sharp, octave, data in re.findall(r'"([A-G])(#?)(-?\d+)"\s*:\s*"data:audio/[^;]+;base64,([^"\s]+)"', BANK.read_text()):
        pitch = 12 * (int(octave) + 1) + 'C D EF G A B'.index(letter) + bool(sharp)
        wave, rate = sf.read(io.BytesIO(base64.b64decode(data, validate=True)), dtype='float32', always_2d=True)
        if rate != RATE:
            raise ValueError(f'{pitch}: expected {RATE} Hz, got {rate}')
        bank[pitch] = wave
    return bank


def key_sample(bank, pitch):
    key = min(bank, key=lambda p: (abs(p - pitch), p))
    mono = bank[key].mean(axis=1).astype('float64')
    if pitch != key:
        pos = np.arange(0, len(mono) - 1, 2 ** ((pitch - key) / 12))
        mono = np.interp(pos, np.arange(len(mono)), mono)
    attack = round(0.004 * RATE)
    mono[:attack] *= np.linspace(0, 1, attack)
    return mono


def profile(bank, pitch):
    mono = key_sample(bank, pitch)
    total = np.r_[0., np.cumsum(mono ** 2)][FRAMES.clip(max=len(mono))] / RATE

    blocks = mono[:len(mono) // 128 * 128].reshape(-1, 128)
    def box_power(size):
        return (blocks.reshape(len(blocks), -1, size).mean(axis=2) ** 2).mean(axis=1)

    def block_energy(power):
        # Spread each block's measured energy uniformly over its 128 samples.
        energy = np.r_[0., np.cumsum(power)] * (128 / RATE)
        return np.interp(FRAMES / 128, np.arange(len(energy)), energy)

    low = block_energy(box_power(128))
    mid = block_energy((box_power(8) - box_power(64)).clip(min=0))
    curves = np.array([total, low, mid])
    return quantize_curve(curves, pitch)


def quantize_curve(curves, pitch):
    unit = curves[:, -1] / 65535
    if not np.all(unit > 0):
        raise ValueError(f'{pitch}: silent calibration band')
    return unit, np.rint(curves / unit[:, None]).astype('uint16')


def pitched_attack_db(bank, pitch):
    # Same clock, window and partial weights as expressive_salience.rs.
    mono = key_sample(bank, pitch)
    mono = mono[:len(mono) // 8 * 8].reshape(-1, 8).mean(axis=1)
    rate, width = RATE / 8, 640
    hz = 440 * 2**((pitch - 69) / 12) * np.array([1, 2, 3])
    weights = np.where(hz < .46 * rate, [1., .35, .12], 0.)
    if not weights[0]:
        return 0  # Outside the analysis band; never queried by the detector.
    kernel = np.exp(-2j * np.pi * hz[:, None] * np.arange(width) / rate) * np.hanning(width)
    power = np.mean([weights @ abs(kernel @ mono[i:i+width])**2 for i in (0, 140, 350, 600)])
    return round(1000 * np.log10(power))  # hundredths of a dB


def reference(bank, dest):
    """Pack only the register used by the attack meter, with each key's own scale."""
    from scipy.signal import resample_poly
    offsets, scales, samples = [0], [], []
    for pitch in range(21, 99):
        wave = resample_poly(key_sample(bank, pitch), 1, 8)
        scale = np.max(np.abs(wave))
        codes = np.rint(np.sign(wave) * 127 * np.log1p(255 * np.abs(wave) / scale) / np.log(256))
        samples.append(codes.astype('int8').tobytes())
        offsets.append(offsets[-1] + len(wave))
        scales.append(scale)
    with Path(dest).open('wb') as out:
        out.write(np.asarray(offsets, dtype='<u4').tobytes())
        out.write(np.asarray(scales, dtype='<f4').tobytes())
        out.writelines(samples)


def spectra(bank):
    # Sixteen strongest FFT bins of each ringing key. Store bin number and
    # the high 16 bits of float32 power; relative quantization error < 0.8%.
    width = 1024
    ages = AGES
    window = np.hanning(width)
    hz = np.fft.rfftfreq(width, 8 / RATE)
    f = np.maximum(hz, 1)
    bands = np.array([np.exp(-(f/170)**4), 1/((1+(280/f)**6)*(1+(f/1800)**6)), 1/(1+(100/f)**6)])
    print('// Generated by tools/calibrate_medley_piano.py --spectra.')
    print(f'const AGES: [f64; {len(ages)}] = {ages};')
    print('#[rustfmt::skip]')
    # MIDI 99 and above have fundamentals outside the calibrated passband.
    print('static KEYS: [Template; 78 * AGES.len()] = [')
    for pitch in range(21, 99):
        mono = key_sample(bank, pitch)
        dec = mono[:len(mono)//8*8].reshape(-1, 8).mean(axis=1)
        dec = np.pad(dec, (width, width))
        for age in ages:
            at = round(age * RATE / 8) + width//2
            frame = dec[at:at+width]
            power = abs(np.fft.rfft(np.pad(frame, (0, width-len(frame))) * window))**2
            register = (bands @ power).astype(np.float32).view(np.uint32) >> 16
            power[:2] = 0
            power[hz > 2480] = 0
            bins = np.argsort(-power, kind='stable')[:16]
            packed = (bins << 16) | (power[bins].astype(np.float32).view(np.uint32) >> 16)
            print('    Template::decode([' + ', '.join(hex(int(i)) for i in packed)
                  + '], ' + str(register.tolist()) + '),')
    print('];')


def recording_profile(bank, pitch):
    from scipy.signal import sosfilt
    # Same cascaded Butterworth sections as expressive_recording.rs, here
    # applied to the actual piano sample before integrating its decay.
    mono = key_sample(bank, pitch)
    def section(hz, sign):
        w = 2*np.pi*hz/RATE
        a = 1 + np.sin(w)/np.sqrt(2)
        b = (1 - sign*np.cos(w))/(2*a)
        return [b, 2*sign*b, b, 1, -2*np.cos(w)/a, (2-a)/a]
    curves = []
    for low, high in [(100, 4800), (40, 165), (280, 1800)]:
        filtered = sosfilt([section(low, -1), section(high, 1)], mono)
        curves.append(np.r_[0., np.cumsum(filtered**2)][FRAMES.clip(max=len(mono))] / RATE)
    return quantize_curve(np.array(curves), pitch)


def emit_profiles(bank, name, measure):
    print('#[rustfmt::skip]')
    print(f'const {name}: [Profile; 88] = [')
    for pitch in range(21, 109):
        unit, codes = measure(bank, pitch)
        # Each CDF starts at zero. Keep its other 15 knots; all keys and bands
        # retain their own scale so quiet treble notes do not lose precision.
        scales = ', '.join('%.9e' % x for x in unit)
        rows = ', '.join('[' + ', '.join(map(str, row[1:])) + ']' for row in codes)
        print(f'    Profile {{ unit: [{scales}], cdf: [{rows}] }},')
    print('];')


if __name__ == '__main__':
    bank = load_bank()
    if len(sys.argv) == 3 and sys.argv[1] == '--reference':
        reference(bank, sys.argv[2])
        sys.exit(0)
    if sys.argv[1:] == ['--spectra']:
        spectra(bank)
        sys.exit(0)
    if sys.argv[1:] == ['--bands']:
        print('// Generated by tools/calibrate_medley_piano.py --bands.')
        emit_profiles(bank, 'RECORDING_PROFILES', recording_profile)
        sys.exit(0)
    print('// Generated by tools/calibrate_medley_piano.py; do not edit by hand.')
    print('const TIMES: [f64; %d] = [%s];' % (len(TIMES), ', '.join(map(str, TIMES))))
    emit_profiles(bank, 'PROFILES', profile)
    levels = [pitched_attack_db(bank, p) for p in range(21, 109)]
    print('const ATTACK_DB_X100: [i16; 88] = [')
    for i in range(0, len(levels), 11):
        print('    ' + ', '.join(map(str, levels[i:i+11])) + ',')
    print('];')
